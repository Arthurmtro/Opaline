import Foundation

/// Terminal colors for Ghostty and cmux (which embeds Ghostty): a theme file, a backdrop image and a managed config block.
public struct GhosttyTarget: ThemeTarget {
    public init() {}

    public var info: TargetInfo {
        TargetInfo(
            id: "ghostty",
            name: "Terminal",
            summary: "Ghostty theme, palette and glow backdrop. cmux uses it too.",
            symbol: "terminal",
            appURL: ["Ghostty", "cmux"].map(OpalineEnvironment.current.application).first(where: \.exists),
            bundleIdentifier: "com.mitchellh.ghostty"
        )
    }

    static let blockStart = "# >>> opaline (managed, edits are overwritten) >>>"
    static let blockEnd = "# <<< opaline <<<"

    private func directory(_ context: TargetContext) -> URL { context.environment.url("~/.config/ghostty") }
    private func config(_ context: TargetContext) -> URL { directory(context).appending(path: "config") }
    private func backdrop(_ context: TargetContext) -> URL { directory(context).appending(path: "opaline-backdrop.png") }
    private func themeFile(named name: String, _ context: TargetContext) -> URL { directory(context).appending(path: "themes/\(name)") }

    public func files(in context: TargetContext) -> [URL] {
        [config(context), directory(context).appending(path: "themes/"), backdrop(context)]
    }

    public func isInstalled(in context: TargetContext) -> Bool {
        directory(context).exists
            || context.environment.application("Ghostty").exists
            || context.environment.application("cmux").exists
    }

    public func changes(for theme: Theme, in context: TargetContext) async throws -> [FileChange] {
        var changes = theme.appearances.map { appearance in
            FileChange(url: themeFile(named: theme.variantName(appearance), context), text: Self.themeFile(theme.variant(appearance)))
        }
        if theme.alternate == nil {
            changes.append(FileChange(url: backdrop(context), contents: BackdropRenderer.render(theme: theme, width: 2560, height: 1440)))
        }
        let current = context.read(config(context)) ?? ""
        changes.append(FileChange(url: config(context), text: Self.config(current, theme: theme, backdrop: context.environment.display(backdrop(context)))))
        return changes
    }

    public func didApply(_ theme: Theme, in context: TargetContext) async throws {
        _ = try? await Shell.run(CmuxTarget.cli, ["reload-config"])
    }

    static func themeFile(_ theme: Theme) -> String {
        let palette = theme.palette
        let ansi = theme.terminal.ansi.enumerated().map { "palette = \($0.offset)=\($0.element.opaqueHex)" }
        return ([
            "# \(theme.name), generated by Opaline.",
            "background = \(palette.base.opaqueHex)",
            "foreground = \(palette.text.opaqueHex)",
            "cursor-color = \(palette.accent.opaqueHex)",
            "cursor-text = \(palette.base.opaqueHex)",
            "selection-background = \(palette.selection.opaqueHex)",
            "selection-foreground = \(palette.text.opaqueHex)",
            "",
        ] + ansi).joined(separator: "\n") + "\n"
    }

    /// Replaces the managed block, or appends it. Ghostty keeps the last value of a key, so the block wins.
    /// A theme with both appearances follows the Mac (`light:…,dark:…`). Ghostty has one background image for both, so the
    /// block resets it (an empty value restores the default): an image set earlier in the file would hide the light variant.
    static func config(_ current: String, theme: Theme, backdrop: String) -> String {
        let settings = theme.alternate == nil
            ? [
                "theme = \(theme.name)",
                "background-image = \(backdrop)",
                "background-image-fit = cover",
                "background-image-position = bottom-right",
                "background-image-opacity = 1",
            ]
            : [
                "theme = light:\(theme.variantName(.light)),dark:\(theme.variantName(.dark))",
                "background-image =",
            ]
        let block = ([blockStart] + settings + [blockEnd]).joined(separator: "\n")
        return ManagedBlock.replace(in: current, start: blockStart, end: blockEnd, with: block)
    }
}

enum ManagedBlock {
    /// Swaps the text between `start` and `end` markers (inclusive), or appends `block` at the end.
    static func replace(in text: String, start: String, end: String, with block: String) -> String {
        if let startRange = text.range(of: start), let endRange = text.range(of: end, range: startRange.upperBound..<text.endIndex) {
            return text.replacingCharacters(in: startRange.lowerBound..<endRange.upperBound, with: block)
        }
        let separator = text.isEmpty || text.hasSuffix("\n\n") ? "" : (text.hasSuffix("\n") ? "\n" : "\n\n")
        return text + separator + block + "\n"
    }
}
